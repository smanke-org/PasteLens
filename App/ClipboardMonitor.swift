import AppKit
import PasteLensKit

/// Watches the system clipboard and records each new copy.
@MainActor
final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount
    /// The change count of what PasteLens itself just wrote, so it isn't recorded again.
    var ownChangeCount = -1
    /// Recent clippings skipped for size, with when — shown in the menu so nothing vanishes silently.
    private(set) var lastSkipped: String?

    func start() {
        timer?.invalidate()
        let timer = Timer(timeInterval: 0.25, repeats: true) { _ in
            MainActor.assumeIsolated { ClipboardMonitor.shared.poll() }
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChange else { return }
        lastChange = count
        guard count != ownChangeCount else { return }
        capture(pasteboard)
    }

    /// Reads the clipboard right now (used after "copy to stack" sends ⌘C).
    func captureNow() -> Clipping? {
        let pasteboard = NSPasteboard.general
        lastChange = pasteboard.changeCount
        return capture(pasteboard)
    }

    @discardableResult
    private func capture(_ pasteboard: NSPasteboard) -> Clipping? {
        let prefs = Preferences.shared
        guard !prefs.paused, let items = pasteboard.pasteboardItems, let first = items.first else { return nil }
        let typeNames = Set(first.types.map(\.rawValue))
        if typeNames.contains(UTI.ownMarker) { return nil }
        // Password managers and others mark what shouldn't be kept.
        if !typeNames.isDisjoint(with: [UTI.concealed, UTI.transient, UTI.autoGenerated]) { return nil }

        let front = NSWorkspace.shared.frontmostApplication
        var source: (bundleID: String?, name: String?) = (front?.bundleIdentifier, front?.localizedName)
        if let declared = first.string(forType: NSPasteboard.PasteboardType(UTI.source)), !declared.isEmpty {
            source.bundleID = declared
            if let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: declared) {
                source.name = FileManager.default.displayName(atPath: url.path).replacingOccurrences(of: ".app", with: "")
            }
        }
        if let id = source.bundleID, prefs.ignoredApps.contains(id) { return nil }

        var representations: [ClipRepresentation] = []
        let fileURLs = items.compactMap { $0.string(forType: .fileURL) }
        if fileURLs.count > 0 {
            guard prefs.captureFiles else { return nil }
            representations = fileURLs.map { ClipRepresentation(type: UTI.fileURL, data: Data($0.utf8)) }
            if let text = first.string(forType: .string) { representations.append(ClipRepresentation(type: UTI.plainText, data: Data(text.utf8))) }
        } else {
            for type in first.types {
                let name = type.rawValue
                // Dynamic types are private to the app that made them; the source marker is metadata.
                if name.hasPrefix("dyn.") || name == UTI.source || name.hasPrefix("com.apple.pasteboard.promised") { continue }
                if let data = first.data(forType: type), !data.isEmpty {
                    representations.append(ClipRepresentation(type: name, data: data))
                }
            }
        }
        guard !representations.isEmpty else { return nil }
        let content = ClipContent(representations: representations)
        let isImage = content.plainText == nil && content.types.contains { UTI.imageTypes.contains($0) }
        if isImage && !prefs.captureImages { return nil }

        let limit = Int(prefs.maxClipMB * 1_048_576)
        if limit > 0, content.sizeBytes > limit {
            lastSkipped = "\(ByteCountFormatter.string(fromByteCount: Int64(content.sizeBytes), countStyle: .file)) from \(source.name ?? "an app")"
            NSLog("PasteLens: skipped a \(content.sizeBytes)-byte clipping over the \(limit)-byte limit")
            return nil
        }

        var finding: SensitiveScanner.Finding?
        if prefs.detectSensitive, let text = content.plainText { finding = SensitiveScanner.scan(text) }
        let clip = ClipStore.shared.record(content, source: source, imageSize: isImage ? ClipStore.imageSize(content) : nil,
                                           sensitive: finding)
        SoundPlayer.play(.copy)
        StackController.shared.didCopy(clip)
        return clip
    }
}

enum SoundPlayer {
    enum Event { case copy, paste, delete, save, stackAdd, stackPaste, error }

    @MainActor static func play(_ event: Event) {
        guard Preferences.shared.sounds else { return }
        let name: String
        switch event {
        case .copy: name = "Tink"
        case .paste: name = "Pop"
        case .delete: name = "Bottle"
        case .save: name = "Purr"
        case .stackAdd: name = "Morse"
        case .stackPaste: name = "Pop"
        case .error: name = "Funk"
        }
        guard let sound = NSSound(named: NSSound.Name(name))?.copy() as? NSSound else { return }
        sound.volume = event == .error ? 0.6 : 0.25
        sound.play()
    }
}
