import Foundation

/// What a clipping mainly holds, chosen from its richest useful representation.
public enum ClipKind: String, Codable, CaseIterable, Sendable {
    case text, richText, url, color, image, file, other

    public var label: String {
        switch self {
        case .text: "Text"
        case .richText: "Rich Text"
        case .url: "Link"
        case .color: "Color"
        case .image: "Image"
        case .file: "File"
        case .other: "Other"
        }
    }

    public var symbol: String {
        switch self {
        case .text: "text.alignleft"
        case .richText: "textformat"
        case .url: "link"
        case .color: "paintpalette"
        case .image: "photo"
        case .file: "doc"
        case .other: "questionmark.square.dashed"
        }
    }
}

/// One pasteboard flavor of a clipping, exactly as it was copied.
public struct ClipRepresentation: Codable, Hashable, Sendable {
    public var type: String
    public var data: Data
    public init(type: String, data: Data) {
        self.type = type
        self.data = data
    }
}

/// The bytes of a clipping. Stored apart from its metadata, so the library index stays small.
public struct ClipContent: Codable, Hashable, Sendable {
    public var representations: [ClipRepresentation]
    public init(representations: [ClipRepresentation]) { self.representations = representations }

    public func data(for type: String) -> Data? { representations.first { $0.type == type }?.data }
    public var types: [String] { representations.map(\.type) }
    public var sizeBytes: Int { representations.reduce(0) { $0 + $1.data.count } }

    /// The plain text a clipping carries, if any.
    public var plainText: String? {
        for type in UTI.textTypes {
            if let data = data(for: type), let s = String(data: data, encoding: .utf8) { return s }
        }
        return nil
    }

    public static func text(_ string: String) -> ClipContent {
        ClipContent(representations: [ClipRepresentation(type: UTI.plainText, data: Data(string.utf8))])
    }
}

/// Uniform type identifiers PasteLens cares about.
public enum UTI {
    public static let plainText = "public.utf8-plain-text"
    public static let legacyText = "NSStringPboardType"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let pdf = "com.adobe.pdf"
    public static let fileURL = "public.file-url"
    public static let url = "public.url"
    public static let color = "com.apple.cocoa.pasteboard.color"

    /// Marks what PasteLens itself put on the pasteboard, so it isn't recorded again.
    public static let ownMarker = "com.smanke.PasteLens.own"
    /// Conventions from nspasteboard.org that password managers and others set.
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    public static let source = "org.nspasteboard.source"
    /// Set on Universal Clipboard items, whose data comes from another device only when read.
    public static let remoteClipboard = "com.apple.is-remote-clipboard"

    public static let textTypes = [plainText, legacyText, "public.text", "public.plain-text"]
    public static let imageTypes = [png, tiff, jpeg, heic, pdf]
}

/// A thing that was copied. Metadata only; the bytes live in `ClipContent`.
public struct Clipping: Codable, Identifiable, Hashable, Sendable {
    public var id: UUID
    public var createdAt: Date
    /// When it was last copied or pasted; history is ordered by this.
    public var copiedAt: Date
    /// When any field last changed, for last-writer-wins merging across Macs.
    public var updatedAt: Date
    public var kind: ClipKind
    public var types: [String]
    public var preferredType: String
    public var sizeBytes: Int
    /// The first 2,048 characters of the text, or a file list, link or color.
    public var previewText: String
    public var textLength: Int
    public var ocrText: String?
    public var title: String?
    public var note: String?
    public var sourceBundleID: String?
    public var sourceName: String?
    public var imageWidth: Int?
    public var imageHeight: Int?
    /// SHA-256 of the content, to spot the same thing copied twice.
    public var contentHash: String
    /// Whether it is part of the rolling history (the "History" pastebin).
    public var inHistory: Bool
    /// Custom pastebins it has been saved into. Saved clippings never expire.
    public var pastebinIDs: [UUID]
    public var pinned: Bool
    /// Looked like a secret (key, card number, one-time code); masked, never synced, deleted soon.
    public var sensitive: Bool
    public var expiresAt: Date?
    /// Device that first recorded it.
    public var origin: String

    public init(id: UUID = UUID(), createdAt: Date = Date(), kind: ClipKind, types: [String], preferredType: String,
                sizeBytes: Int, previewText: String, textLength: Int, contentHash: String, origin: String) {
        self.id = id
        self.createdAt = createdAt
        self.copiedAt = createdAt
        self.updatedAt = createdAt
        self.kind = kind
        self.types = types
        self.preferredType = preferredType
        self.sizeBytes = sizeBytes
        self.previewText = previewText
        self.textLength = textLength
        self.contentHash = contentHash
        self.inHistory = true
        self.pastebinIDs = []
        self.pinned = false
        self.sensitive = false
        self.origin = origin
    }

    /// Kept no matter what the history limits say.
    public var isKept: Bool { pinned || !pastebinIDs.isEmpty }

    /// The text to search: preview, recognized text, title and note.
    public var searchableText: String {
        [title, previewText, ocrText, note, sourceName].compactMap { $0 }.joined(separator: "\n")
    }

    public var displayTitle: String {
        if let title, !title.isEmpty { return title }
        let line = previewText.split(whereSeparator: \.isNewline).first.map(String.init) ?? previewText
        let trimmed = line.trimmingCharacters(in: .whitespaces)
        if !trimmed.isEmpty { return trimmed }
        if kind == .image, let w = imageWidth, let h = imageHeight { return "Image \(w)×\(h)" }
        return kind.label
    }
}

public struct Pastebin: Codable, Identifiable, Hashable, Sendable {
    public var id: UUID
    public var name: String
    public var symbol: String
    public var colorName: String
    public var order: Double
    public var showInQuickPaste: Bool
    public var hotKey: StoredHotKey?
    public var updatedAt: Date

    public init(id: UUID = UUID(), name: String, symbol: String = "tray.full", colorName: String = "blue",
                order: Double = 0) {
        self.id = id
        self.name = name
        self.symbol = symbol
        self.colorName = colorName
        self.order = order
        self.showInQuickPaste = true
        self.updatedAt = Date()
    }

    /// The rolling history every copy lands in.
    public static let historyID = UUID(uuidString: "00000000-0000-0000-0000-00000000A11E")!
    /// Pinned clippings, from any pastebin.
    public static let pinnedID = UUID(uuidString: "00000000-0000-0000-0000-0000000019ED")!
}

/// A keyboard shortcut as stored data (Carbon key code and modifiers), shared with the app's HotKey.
public struct StoredHotKey: Codable, Hashable, Sendable {
    public var keyCode: UInt32
    public var modifiers: UInt32
    public var display: String
    public init(keyCode: UInt32, modifiers: UInt32, display: String) {
        self.keyCode = keyCode
        self.modifiers = modifiers
        self.display = display
    }
}

/// A text snippet with placeholders, optionally expanded from a typed abbreviation.
public struct Snippet: Codable, Identifiable, Hashable, Sendable {
    public var id: UUID
    public var name: String
    public var abbreviation: String
    public var template: String
    public var group: String
    public var updatedAt: Date

    public init(id: UUID = UUID(), name: String, abbreviation: String = "", template: String, group: String = "") {
        self.id = id
        self.name = name
        self.abbreviation = abbreviation
        self.template = template
        self.group = group
        self.updatedAt = Date()
    }
}

/// Everything PasteLens keeps besides clipping bytes.
public struct Library: Codable, Sendable {
    public var clippings: [Clipping] = []
    public var pastebins: [Pastebin] = []
    public var smartPastebins: [SmartPastebin] = []
    public var filters: [Filter] = []
    public var snippets: [Snippet] = []
    /// Ids of things deleted here or elsewhere, with when, so a sync can't bring them back.
    public var tombstones: [String: Date] = [:]
    public var seededDefaults = false
    /// Global shortcuts that paste one particular clipping. Kept on this Mac.
    public var clipHotKeys: [UUID: StoredHotKey] = [:]

    public init() {}

    enum CodingKeys: String, CodingKey { case clippings, pastebins, smartPastebins, filters, snippets, tombstones, seededDefaults, clipHotKeys }

    /// Tolerates fields added in later versions being absent.
    public init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        clippings = try c.decodeIfPresent([Clipping].self, forKey: .clippings) ?? []
        pastebins = try c.decodeIfPresent([Pastebin].self, forKey: .pastebins) ?? []
        smartPastebins = try c.decodeIfPresent([SmartPastebin].self, forKey: .smartPastebins) ?? []
        filters = try c.decodeIfPresent([Filter].self, forKey: .filters) ?? []
        snippets = try c.decodeIfPresent([Snippet].self, forKey: .snippets) ?? []
        tombstones = try c.decodeIfPresent([String: Date].self, forKey: .tombstones) ?? [:]
        seededDefaults = try c.decodeIfPresent(Bool.self, forKey: .seededDefaults) ?? false
        clipHotKeys = try c.decodeIfPresent([UUID: StoredHotKey].self, forKey: .clipHotKeys) ?? [:]
    }
}
